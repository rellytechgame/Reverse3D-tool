from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest
import trimesh

from reverse3d.config import Settings
from reverse3d.errors import InputValidationError
from reverse3d.reverse_eng.geometry_fit import (
    detect_primitives,
    fit_cylinder,
    fit_plane,
    fit_primitives_file,
    fit_sphere,
)
from reverse3d.reverse_eng.parametric import export_parametric, generate_cadquery, generate_openscad

RNG = np.random.default_rng(7)


def _noisy(points: np.ndarray, sigma: float = 0.002) -> np.ndarray:
    return points + RNG.normal(0, sigma, points.shape)


def test_plane() -> None:
    xy = RNG.uniform(-1, 1, (2000, 2))
    pts = _noisy(np.column_stack([xy, 0.5 * xy[:, 0] + 2.0]))
    fit = fit_plane(pts, threshold=0.01)
    assert fit is not None
    n = np.array(fit.params["normal"])
    expected = np.array([-0.5, 0.0, 1.0]) / np.linalg.norm([-0.5, 0.0, 1.0])
    assert abs(n @ expected) == pytest.approx(1.0, abs=1e-3)
    assert fit.inlier_ratio > 0.95


def test_sphere() -> None:
    sphere = trimesh.creation.icosphere(subdivisions=4, radius=3.0)
    sphere.apply_translation([1, 2, 3])
    pts, idx = trimesh.sample.sample_surface(sphere, 3000, seed=1)
    fit = fit_sphere(_noisy(pts), sphere.face_normals[idx], threshold=0.02)
    assert fit is not None
    assert fit.params["radius"] == pytest.approx(3.0, rel=0.01)
    assert fit.params["center"] == pytest.approx([1, 2, 3], abs=0.02)


def test_cylinder() -> None:
    cyl = trimesh.creation.cylinder(radius=2.0, height=10.0, sections=128)
    cyl.apply_transform(trimesh.transformations.rotation_matrix(0.6, [1, 0, 0]))
    pts, idx = trimesh.sample.sample_surface(cyl, 4000, seed=2)
    normals = cyl.face_normals[idx]
    true_axis = np.array([0.0, -np.sin(0.6), np.cos(0.6)])  # R_x(0.6) @ +Z
    side = np.abs(normals @ true_axis) < 0.5  # drop the end caps
    fit = fit_cylinder(pts[side], normals[side], threshold=0.02)
    assert fit is not None
    assert fit.params["radius"] == pytest.approx(2.0, rel=0.02)
    axis = np.array(fit.params["axis_direction"])
    assert abs(axis @ true_axis) == pytest.approx(1.0, abs=1e-2)
    assert fit.params["height"] == pytest.approx(10.0, rel=0.03)


def test_cylinder_requires_normals() -> None:
    assert fit_cylinder(RNG.random((100, 3)), None, threshold=0.1) is None


def test_detect_box_faces() -> None:
    box = trimesh.creation.box(extents=(4, 3, 2))
    pts, idx = trimesh.sample.sample_surface(box, 6000, seed=3)
    report = detect_primitives(pts, box.face_normals[idx], kinds=("plane",), max_primitives=6)
    assert len(report.primitives) == 6
    assert report.unexplained_ratio < 0.05
    assert all(p.kind == "plane" for p in report.primitives)


def test_detect_validation() -> None:
    with pytest.raises(InputValidationError):
        detect_primitives(np.zeros((5, 3)))
    with pytest.raises(InputValidationError):
        detect_primitives(RNG.random((100, 3)), kinds=("cone",))  # type: ignore[arg-type]


def test_mixed_part_and_parametric(tmp_path: Path, settings: Settings) -> None:
    plate = trimesh.creation.box(extents=(20, 20, 2))
    boss = trimesh.creation.cylinder(radius=3, height=10, sections=96)
    boss.apply_translation([0, 0, 6])
    path = tmp_path / "part.stl"
    trimesh.util.concatenate([plate, boss]).export(path)

    report = fit_primitives_file(path, settings, sample_count=15000, max_primitives=6)
    kinds = [p.kind for p in report.primitives]
    assert "plane" in kinds and "cylinder" in kinds
    cyl = next(p for p in report.primitives if p.kind == "cylinder")
    assert cyl.params["radius"] == pytest.approx(3.0, rel=0.05)

    scad = generate_openscad(report)
    assert "cylinder(h=" in scad and "multmatrix(" in scad
    cq = generate_cadquery(report)
    assert "import cadquery as cq" in cq and ".circle(" in cq
    compile(cq, "generated.py", "exec")  # syntactically valid Python

    out = export_parametric(report, tmp_path / "part.scad")
    assert out.read_text().startswith("// Auto-generated by reverse3d")
    with pytest.raises(InputValidationError):
        export_parametric(report, tmp_path / "part.sh")
