"""Generate parametric CAD source (OpenSCAD / CadQuery) from fitted primitives.

The output is a *starting point* for a CAD redesign: each detected primitive
becomes a named, editable feature. Only numeric values coming from the fit are
emitted (formatted floats), so no user/agent text can be injected into the
generated program.
"""

from __future__ import annotations

import math
from pathlib import Path
from typing import Any

import numpy as np

from reverse3d._version import __version__
from reverse3d.errors import InputValidationError
from reverse3d.reverse_eng.geometry_fit import FitReport, PrimitiveFit, plane_basis
from reverse3d.security import prepare_output_file

PARAMETRIC_EXTENSIONS = frozenset({".scad", ".py"})


def _f(x: Any) -> str:
    """Format a number. ``float()`` guarantees only numeric text is emitted."""
    return f"{float(x):.6g}"


def _vec(values: object) -> np.ndarray:
    return np.asarray(values, dtype=np.float64).reshape(3)


def _v3(values: np.ndarray) -> str:
    return ", ".join(_f(x) for x in values)


def _slab_thickness(report: FitReport) -> float:
    return max(report.threshold * 2, 1e-3)


def _rotation_from_z(axis: np.ndarray) -> tuple[float, np.ndarray]:
    """Angle (deg) and rotation vector that map +Z onto ``axis``."""
    z = np.array([0.0, 0.0, 1.0])
    axis = axis / np.linalg.norm(axis)
    cross = np.cross(z, axis)
    if np.linalg.norm(cross) < 1e-9:
        return (
            (0.0, np.array([1.0, 0.0, 0.0])) if axis[2] > 0 else (180.0, np.array([1.0, 0.0, 0.0]))
        )
    angle = math.degrees(math.acos(float(np.clip(z @ axis, -1.0, 1.0))))
    return angle, cross / np.linalg.norm(cross)


def _openscad_feature(idx: int, fit: PrimitiveFit, slab: float) -> str:
    p = fit.params
    header = f"// [{idx}] {fit.kind}  inliers={fit.inliers}  rmse={_f(fit.rmse)}"
    if fit.kind == "sphere":
        center = _v3(_vec(p["center"]))
        return f"{header}\ntranslate([{center}]) sphere(r={_f(p['radius'])});"
    if fit.kind == "cylinder":
        base, axis = _vec(p["axis_point"]), _vec(p["axis_direction"])
        angle, rot = _rotation_from_z(axis)
        return (
            f"{header}\ntranslate([{_v3(base)}]) rotate(a={_f(angle)}, v=[{_v3(rot)}]) "
            f"cylinder(h={_f(p['height'])}, r={_f(p['radius'])});"
        )
    normal, centroid = _vec(p["normal"]), _vec(p["centroid"])
    u, v = plane_basis(normal)
    ex, ey = np.asarray(p["extent_2d"], dtype=np.float64).reshape(2)
    rows = [
        [u[0], v[0], normal[0], centroid[0]],
        [u[1], v[1], normal[1], centroid[1]],
        [u[2], v[2], normal[2], centroid[2]],
        [0, 0, 0, 1],
    ]
    matrix = "[" + ", ".join("[" + ", ".join(_f(x) for x in r) + "]" for r in rows) + "]"
    return f"{header}\nmultmatrix({matrix}) cube([{_f(ex)}, {_f(ey)}, {_f(slab)}], center=true);"


def generate_openscad(report: FitReport) -> str:
    """Return an OpenSCAD program with one feature per detected primitive."""
    slab = _slab_thickness(report)
    features = "\n\n".join(
        _openscad_feature(i, fit, slab) for i, fit in enumerate(report.primitives)
    )
    return (
        f"// Auto-generated by reverse3d {__version__} (https://voxel.lat)\n"
        "// Draft reconstruction from RANSAC primitive fitting. Review before manufacturing.\n"
        f"// points={report.point_count}  threshold={_f(report.threshold)}  "
        f"unexplained={report.unexplained_ratio}\n"
        "$fn = 96;\n\n"
        f"union() {{\n{_indent(features)}\n}}\n"
    )


def _cadquery_feature(idx: int, fit: PrimitiveFit, slab: float) -> str:
    p = fit.params
    name = f"f{idx}_{fit.kind}"
    if fit.kind == "sphere":
        return (
            f"{name} = cq.Workplane('XY').sphere({_f(p['radius'])})"
            f".translate(({_v3(_vec(p['center']))}))"
        )
    if fit.kind == "cylinder":
        base, axis = _vec(p["axis_point"]), _vec(p["axis_direction"])
        u, _ = plane_basis(axis)
        return (
            f"{name} = (cq.Workplane(cq.Plane(origin=({_v3(base)}), xDir=({_v3(u)}), "
            f"normal=({_v3(axis)})))"
            f".circle({_f(p['radius'])}).extrude({_f(p['height'])}))"
        )
    normal, centroid = _vec(p["normal"]), _vec(p["centroid"])
    u, _ = plane_basis(normal)
    ex, ey = np.asarray(p["extent_2d"], dtype=np.float64).reshape(2)
    return (
        f"{name} = (cq.Workplane(cq.Plane(origin=({_v3(centroid)}), xDir=({_v3(u)}), "
        f"normal=({_v3(normal)})))"
        f".rect({_f(ex)}, {_f(ey)}).extrude({_f(slab / 2)}, both=True))"
    )


def generate_cadquery(report: FitReport) -> str:
    """Return a CadQuery (Python) script building the detected primitives."""
    slab = _slab_thickness(report)
    lines = [_cadquery_feature(i, fit, slab) for i, fit in enumerate(report.primitives)]
    names = [f"f{i}_{fit.kind}" for i, fit in enumerate(report.primitives)]
    union = names[0] + "".join(f".union({n})" for n in names[1:]) if names else "cq.Workplane('XY')"
    return (
        f'"""Auto-generated by reverse3d {__version__} (https://voxel.lat).\n\n'
        "Draft reconstruction from RANSAC primitive fitting. Review before manufacturing.\n"
        'Run with CadQuery (pip install cadquery) or open in CQ-editor.\n"""\n\n'
        "import cadquery as cq\n\n" + "\n".join(lines) + f"\n\nresult = {union}\n"
        "cq.exporters.export(result, 'reverse3d_model.step')\n"
    )


def export_parametric(
    report: FitReport, output_path: str | Path, *, overwrite: bool = False
) -> Path:
    """Write OpenSCAD (``.scad``) or CadQuery (``.py``) source for ``report``."""
    if not report.primitives:
        raise InputValidationError("No primitives to export.")
    out = prepare_output_file(
        output_path, allowed_extensions=PARAMETRIC_EXTENSIONS, overwrite=overwrite
    )
    code = generate_openscad(report) if out.suffix.lower() == ".scad" else generate_cadquery(report)
    out.write_text(code, encoding="utf-8")
    return out


def _indent(text: str, spaces: int = 4) -> str:
    pad = " " * spaces
    return "\n".join(pad + line if line else line for line in text.splitlines())
